"""Prepare TT100K (2016 annotations) in YOLO format with the standard 45-class protocol.

Protocol:
  * Classes: categories with > MIN_INST instances in official train+test (= the standard 45 classes).
  * Official split kept: train -> train/val, test -> test (never used for tuning).
  * 6 images exist identically in BOTH official train/ and test/ folders; they are kept in test only.
  * Val = VAL_FRAC of train, random with fixed seed, re-drawn until every class appears in val.
  * Objects of the other 176 classes are dropped (treated as background), as in the common protocol.
  * Images are hard-linked (no extra disk space) into <out>/images/{train,val,test}; labels in <out>/labels/...

Usage:
  python prepare_tt100k.py --src D:/Traffic_sign_dataset/data/data --out D:/Traffic_sign_dataset/processed/TT100K45
"""
import argparse, collections, csv, json, os, random, shutil

MIN_INST = 100
VAL_FRAC = 0.10
SEED = 0


def link_or_copy(src, dst):
    if os.path.exists(dst):
        return
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    ann = json.load(open(os.path.join(a.src, "annotations.json"), encoding="utf-8"))
    imgs = ann["imgs"]
    ids = {sp: set(open(os.path.join(a.src, sp, "ids.txt")).read().split()) for sp in ("train", "test")}
    overlap = ids["train"] & ids["test"]
    train_ids = sorted(ids["train"] - overlap)
    test_ids = sorted(ids["test"])

    cnt = collections.Counter(o["category"] for i in ids["train"] | ids["test"] for o in imgs[i]["objects"])
    names = sorted(k for k, v in cnt.items() if v > MIN_INST)
    assert len(names) == 45, f"expected 45 classes, got {len(names)}"
    cid = {n: k for k, n in enumerate(names)}

    # val split: re-draw until every class has >= 1 instance in val
    rng = random.Random(SEED)
    for attempt in range(1000):
        shuffled = train_ids[:]
        rng.shuffle(shuffled)
        nval = round(VAL_FRAC * len(shuffled))
        val, tr = sorted(shuffled[:nval]), sorted(shuffled[nval:])
        vc = {o["category"] for i in val for o in imgs[i]["objects"] if o["category"] in cid}
        if len(vc) == 45:
            break
    else:
        raise RuntimeError("could not draw a val split covering all classes")
    splits = {"train": tr, "val": val, "test": test_ids}

    W = H = 2048
    stats = []
    per_class = {sp: collections.Counter() for sp in splits}
    for sp, lst in splits.items():
        idir = os.path.join(a.out, "images", sp)
        ldir = os.path.join(a.out, "labels", sp)
        os.makedirs(idir, exist_ok=True)
        os.makedirs(ldir, exist_ok=True)
        folder = "test" if sp == "test" else "train"
        n_inst = n_empty = 0
        size_bins = collections.Counter()
        for i in lst:
            src = os.path.join(a.src, folder, f"{i}.jpg")
            link_or_copy(src, os.path.join(idir, f"{i}.jpg"))
            lines = []
            for o in imgs[i]["objects"]:
                c = o["category"]
                if c not in cid:
                    continue
                b = o["bbox"]
                x1, y1 = max(0.0, b["xmin"]), max(0.0, b["ymin"])
                x2, y2 = min(W, b["xmax"]), min(H, b["ymax"])
                w, h = x2 - x1, y2 - y1
                if w <= 0 or h <= 0:
                    continue
                lines.append(f"{cid[c]} {(x1 + x2) / 2 / W:.6f} {(y1 + y2) / 2 / H:.6f} {w / W:.6f} {h / H:.6f}")
                per_class[sp][c] += 1
                area = w * h
                size_bins["small" if area < 32 ** 2 else ("medium" if area <= 96 ** 2 else "large")] += 1
            n_inst += len(lines)
            n_empty += not lines
            with open(os.path.join(ldir, f"{i}.txt"), "w") as f:
                f.write("\n".join(lines) + ("\n" if lines else ""))
        stats.append([sp, len(lst), n_empty, n_inst, size_bins["small"], size_bins["medium"], size_bins["large"]])

    with open(os.path.join(a.out, "TT100K45.yaml"), "w", encoding="utf-8") as f:
        f.write(f"# TT100K 2016, 45 classes (> {MIN_INST} instances in train+test), generated by prepare_tt100k.py\n")
        f.write(f"path: {os.path.abspath(a.out).replace(os.sep, '/')}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n")
        for k, n in enumerate(names):
            f.write(f"  {k}: {n}\n")
    with open(os.path.join(a.out, "table1_stats.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["split", "images", "images_without_45class_objects", "instances", "small(<32^2)", "medium", "large(>96^2)",
                    "small_pct", "medium_pct", "large_pct"])
        for r in stats:
            n = max(r[3], 1)
            w.writerow(r + [round(100 * r[4] / n, 2), round(100 * r[5] / n, 2), round(100 * r[6] / n, 2)])
    with open(os.path.join(a.out, "per_class_counts.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["class_id", "class", "train", "val", "test", "total"])
        for k, n in enumerate(names):
            r = [per_class[s][n] for s in ("train", "val", "test")]
            w.writerow([k, n] + r + [sum(r)])
    for sp, lst in splits.items():
        with open(os.path.join(a.out, f"{sp}_ids.txt"), "w") as f:
            f.write("\n".join(lst) + "\n")
    with open(os.path.join(a.out, "excluded_train_overlap_ids.txt"), "w") as f:
        f.write("\n".join(sorted(overlap)) + "\n")
    print("val draw attempts:", attempt + 1)
    for r in stats:
        print(r)


if __name__ == "__main__":
    main()
